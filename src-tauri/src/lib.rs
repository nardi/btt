/// Path of the generated TypeScript bindings, relative to this crate.
pub const TYPESCRIPT_BINDINGS_PATH: &str =
    concat!(env!("CARGO_MANIFEST_DIR"), "/../ui/shared/src/bindings.ts");

/// Collects the commands the frontend may call.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new().commands(collect_commands![
        commands::list_trips,
        commands::create_trip,
        commands::open_trip,
        commands::close_trip,
        commands::apply_trip_edit,
        commands::undo_trip_edit,
        commands::redo_trip_edit,
        commands::add_place_at_coordinates,
        commands::delete_trip,
        commands::search_places,
        commands::list_travellers,
        commands::save_traveller,
        commands::delete_traveller,
        commands::plan_tickets,
        commands::fetch_live_quote,
        problem_report::export_problem_report,
    ])
}

/// Returns the exporter for the TypeScript bindings, so the app and the bindings test write the
/// same file.
pub fn typescript_exporter() -> specta_typescript::Typescript {
    specta_typescript::Typescript::default()
        .header("// Generated by tauri-specta from the Rust types. Do not edit by hand.\n")
}

/// Runs the app until its last window closes.
///
/// # Panics
///
/// Panics when Tauri cannot start, for example because the web view is missing.
pub fn run() {
    // Log lines go to the terminal and, without colour codes, into memory for problem reports.
    let recent_log_lines = RecentLogLines::default();
    tracing_subscriber::registry()
        .with(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| tracing_subscriber::EnvFilter::new("info")),
        )
        .with(tracing_subscriber::fmt::layer())
        .with(
            tracing_subscriber::fmt::layer()
                .with_ansi(false)
                .with_writer(recent_log_lines.clone()),
        )
        .init();

    let specta_builder = specta_builder();
    // Development builds keep the bindings in sync with the Rust types on every start.
    #[cfg(debug_assertions)]
    if let Err(error) = specta_builder.export(typescript_exporter(), TYPESCRIPT_BINDINGS_PATH) {
        tracing::warn!(%error, "could not export TypeScript bindings");
    }

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(specta_builder.invoke_handler())
        .setup(move |app| {
            specta_builder.mount_events(app);
            let data_directory = app.path().app_data_dir()?;
            std::fs::create_dir_all(&data_directory)?;
            let storage = Storage::open(&data_directory.join("btt.sqlite3"))?;
            app.manage(AppState::new(
                app.handle().clone(),
                storage,
                &data_directory,
                recent_log_lines,
            )?);
            probe::start(app.handle());
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("Tauri failed to start");
}
